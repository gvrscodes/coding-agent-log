"""Path validation and security checks for agent docs."""

from pathlib import Path

ALLOWED_FOLDERS: frozenset[str] = frozenset({"code-reviews", "explanations"})


class PathValidationError(Exception):
    """Raised when a requested path violates security or structure constraints."""

    pass


def _ensure_within(target: Path, base: Path) -> Path:
    # Resolve symlinks and relative components to prevent escape from base directory
    resolved_target = target.resolve()
    resolved_base = base.resolve()
    try:
        resolved_target.relative_to(resolved_base)
    except ValueError as exc:
        raise PathValidationError("Path escapes allowed directory") from exc
    return resolved_target


def validate_folder_path(root: Path | str, folder: str) -> Path:
    """Validate that the folder is an allowed doc category under root/docs."""
    if folder not in ALLOWED_FOLDERS:
        raise PathValidationError(f"Invalid folder: {folder}")

    # Docs must remain strictly under the configured project root
    base_docs = Path(root).resolve() / "docs"
    target_folder = base_docs / folder
    return _ensure_within(target_folder, base_docs)


def validate_doc_path(root: Path | str, folder: str, filename: str) -> Path:
    """Validate that the file is an existing markdown document inside allowed folder."""
    # Disallow separators and path navigation tokens in filename
    if "/" in filename or "\\" in filename or filename.startswith("."):
        raise PathValidationError("Filename contains invalid path characters")

    # Only markdown files generated by agents should be served
    if not filename.lower().endswith(".md"):
        raise PathValidationError("Only markdown files are permitted")

    folder_path = validate_folder_path(root, folder)
    target_file = _ensure_within(folder_path / filename, folder_path)

    if not target_file.is_file():
        raise FileNotFoundError(f"File not found: {filename}")

    return target_file
